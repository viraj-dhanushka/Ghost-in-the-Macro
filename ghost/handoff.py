"""``ghost handoff``: write a folder that is ready to become a Git repository for AWS Transform custom.

It executes nothing, calls no AWS service and runs no macro: the VBA is read statically. The kit is
deterministic (same workbook, same bytes) and holds no absolute path. Facts about AWS Transform custom come
from ``docs/AWS_TRANSFORM_FACTS.md``. Nothing here has been run against AWS.
"""
from __future__ import annotations

import re
import shlex
from dataclasses import dataclass
from pathlib import Path

from ghost.ingest.limits import ACCEPTED_FORMATS
from ghost.ingest.triage import SizeProfile, scan_sizes
from ghost.models import VbaModule
from ghost.router.explain import CONFIG_FILE, DEFAULT_DEFINITION, atx_dry_run_command
from ghost.router.route import over_limits, route_for_sizes
from ghost.router.thresholds import DEFAULT_THRESHOLDS, RoutingThresholds, ThresholdError, load_thresholds

__all__ = ["HandoffError", "KitResult", "module_files", "write_kit"]

IMPROVEMENT_URL = "https://docs.aws.amazon.com/transform/latest/userguide/service-improvement.html"
OPT_OUT_URL = "https://docs.aws.amazon.com/organizations/latest/userguide/orgs_manage_policies_ai-opt-out.html"
PRICING_URL = "https://aws.amazon.com/transform/pricing/"
COMMAND_URL = "https://docs.aws.amazon.com/transform/latest/userguide/custom-command-reference.html"


class HandoffError(Exception):
    """A reason the kit was not written, in one line."""


@dataclass(frozen=True)
class KitResult:
    files: list[str]
    mapping_written: bool
    vba_modules: int
    vba_error: str | None
    route: str


def _thresholds() -> RoutingThresholds:
    try:
        return load_thresholds()
    except ThresholdError:
        return DEFAULT_THRESHOLDS


def _over(sizes: SizeProfile) -> bool:
    return over_limits(sizes, _thresholds())


def _read_vba(path: Path) -> tuple[list[VbaModule], str | None]:
    """The VBA modules by the static read, or ([], the reason it could not be read)."""
    from ghost.ingest.vba import extract_vba

    try:
        return list(extract_vba(path)), None
    except Exception as exc:  # noqa: BLE001 - reported in the kit, never invented
        return [], f"{type(exc).__name__}: {exc}".strip()[:200]


def module_files(modules: list[VbaModule]) -> list[tuple[str, str]]:
    """(file name, source) for every module exactly once: safe characters, no leading dot, distinct names
    (compared without regard to case), in a fixed order."""
    used: set[str] = set()
    out: list[tuple[str, str]] = []
    for m in sorted(modules, key=lambda m: (m.name, m.source)):
        base = re.sub(r"[^A-Za-z0-9._-]", "_", m.name).lstrip(".") or "module"
        stem, dot, ext = base.rpartition(".")
        if not dot:
            stem, ext = base, ""
        name, n = base, 1
        while name.lower() in used:
            n += 1
            name = f"{stem}_{n}" + (f".{ext}" if ext else "")
        used.add(name.lower())
        out.append((name, m.source))
    return out


def _semantics_text() -> str:
    root = Path(__file__).resolve().parent.parent
    for p in (root / ".kiro" / "steering" / "excel-semantics.md",
              root / "plugin" / "skills" / "guardrails" / "references" / "excel-semantics.md"):
        if p.is_file():
            text = p.read_text(encoding="utf-8")
            if text.startswith("---"):  # drop the Kiro front matter
                text = text.split("---", 2)[2].lstrip("\n")
            return text.rstrip("\n") + "\n"
    raise HandoffError("the Excel semantics table was not found in this installation")


def _contract(mapping, vba_present: bool, mapping_written: bool) -> str:
    lines = [
        "# GHOST_CONTRACT.md",
        "",
        "The shape the returned Python must have so that the original workbook, recalculated by LibreOffice, "
        "can referee it with `ghost challenge`. This file is written by `ghost handoff` from the workbook.",
        "",
        "## The file",
        "",
        "- One file named `logic.py`, one self-contained file: no other module of yours, no data files, no network, "
        "no reading of the workbook, no randomness, no clock.",
        "- It defines `compute(inputs: dict) -> dict`, a pure function. `ghost challenge` runs this file in its own "
        "process; there is no sandbox.",
        "- It does not start with the line `\"\"\"Generated by Ghost`: that marks code Ghost writes itself, and `ghost challenge` "
        "refuses it.",
        "",
    ]
    if mapping_written:
        lines += ["## Inputs and outputs", "",
                  "The names and cells below come from `mapping.yaml`. They were derived from the workbook; they were "
                  "not confirmed by a person. Check them before you rely on them.", "",
                  "| Name | Cell | Type | Minimum | Maximum |", "|---|---|---|---|---|"]
        for kind, specs in (("input", mapping.inputs), ("output", mapping.outputs)):
            for name, s in specs.items():
                lines.append(f"| `{name}` ({kind}) | {s.cell} | {s.type} | {s.min if s.min is not None else ''} | "
                             f"{s.max if s.max is not None else ''} |")
        lines += ["",
                  "`compute` receives every input name as a key. `integer` inputs arrive as `int`, `decimal` inputs "
                  "as `decimal.Decimal`. It returns a dict with every output name as a key, never `None`, and no "
                  "extra keys are needed.", ""]
    else:
        lines += ["## Inputs and outputs", "",
                  "Not written: the workbook was not loaded (it is over Ghost's limits), so no mapping was derived.", ""]
    lines += [
        "## How values are compared",
        "",
        "- Numbers: absolute tolerance 1e-6. Strings: exact. Excel errors (`#DIV/0!`, `#VALUE!`, `#N/A`, `#REF!`, "
        "`#NAME?`, `#NUM!`, `#NULL!`) are compared by error type: return the error as the string, for example "
        "`\"#DIV/0!\"`, where the workbook gives that error.",
        "- Money and spreadsheet arithmetic use `decimal.Decimal`. Convert a float with `Decimal(repr(x))`, never "
        "`Decimal(x)`. Do not use binary floats for currency.",
        "- Worksheet ROUND is half away from zero, evaluated on 15 significant digits. Do not use Python `round()`.",
        "- Reproduce the workbook's quirks, including a `>` where a neighbouring rule uses `>=`. Do not tidy them: "
        "a difference is reported to a person, who decides.",
        "",
        "## Excel semantics table",
        "",
        "The full table is in `excel-semantics.md` in this folder.",
        "",
    ]
    if vba_present:
        lines += [
            "## VBA",
            "",
            "The VBA is in `vba/`. A worksheet cell that calls a VBA function cannot be calculated by the Referee: "
            "with macros trusted the VBA project loads, but such a cell still evaluates to `#MACRO?` (observed with "
            "LibreOffice 26.8; Excel was not checked). So an output that depends on a VBA function is not verifiable "
            "by the Referee, and `ghost challenge` refuses it with exit 2. Choose outputs that do not.",
            "",
        ]
    lines += ["## What `ghost challenge` does not do", "",
              "It does not consult recorded Decisions, it does not sandbox your code, and it does not check against "
              "Excel (\"not checked in Excel\"). A pass means: no difference was found on the cases it tried, "
              "against LibreOffice's recalculation of the workbook.", ""]
    return "\n".join(lines)


def _run_md(definition: str, sizes: SizeProfile, vba_names: list[str], vba_error: str | None, route,
            mapping_written: bool, reasons: list[str]) -> str:
    cmd = atx_dry_run_command("./RUN.md", definition)
    if vba_error:
        vba_line = "VBA: not readable"
    elif not vba_names:
        vba_line = "VBA: none"
    else:
        vba_line = f"VBA: {sizes.vba_lines} lines in {len(vba_names)} module{'s' if len(vba_names) != 1 else ''} (`vba/`)"
    lines = [
        "# RUN.md: hand this folder to AWS Transform custom, then referee what comes back",
        "",
        "> **Review `vba/` before you upload anything.** Look for passwords, connection strings and file paths, and "
        "remove them. AWS says it may use content from AWS Transform, including the responses and code it "
        f"generates, for service improvement, for example model training ({IMPROVEMENT_URL}). To opt out, configure an "
        f"AI services opt-out policy in AWS Organizations ({OPT_OUT_URL}).",
        "",
        "Nothing in this folder has been run against AWS. Ghost did not run `atx` and called no AWS service to write it.",
        "",
        "## What this kit covers",
        "",
        f"- {vba_line}.",
        "- AWS Transform custom migrates VBA code. Its documentation says nothing about worksheet formulas, cell "
        "counts or workbook size, so the formulas are not part of what you send for conversion.",
    ]
    if route.route == "Ghost converts":
        lines.append("- The route Ghost recommends for this workbook is \"Ghost converts\": you may not need AWS Transform.")
    else:
        lines.append(f"- The route Ghost recommends: {route.route}.")
    for r in reasons:
        lines.append(f"  - {r}")
    if not mapping_written:
        lines += ["- mapping.yaml and rules.md were not written: the workbook was not loaded because it is over "
                  "Ghost's limits. `ghost challenge` loads the workbook, so it cannot referee a workbook this size; "
                  "the returned code can only be reviewed by hand."]
    lines += [
        "",
        "## Steps",
        "",
        "1. Review `vba/` as above. Needs Node.js 22 or later, Git, and the `atx` CLI with AWS credentials that allow "
        "`transform-custom:*` (see the AWS getting-started page).",
        "2. Make this folder a Git repository (AWS Transform custom requires one):",
        "",
        "   ```",
        "   git init",
        "   git add .",
        "   git commit -m \"Hand-off kit\"",
        "   ```",
        "",
        f"3. Suggested command, not run (check it against `atx custom def exec --help` first; "
        f"`-t` approves all tool calls, so work on a copy):",
        "",
        "   ```",
        f"   {cmd}",
        "   ```",
        "",
        f"   `{CONFIG_FILE}` is the `-g` file; its `additionalPlanContext` points the agent at `GHOST_CONTRACT.md`. "
        f"`{definition}` is the AWS-managed definition (Early access); `atx custom def list` shows what your registry "
        f"has. Command reference: {COMMAND_URL}.",
        "4. How to tell whether the run failed: a non-interactive run exits 0 even when the transformation failed "
        "(CLI 3.22.1 and later). Do not read the exit code as a result. Read the conversation log "
        "(`~/.aws/atx/custom/<conversation-id>/logs/`) for the failure message. Ghost has not verified which log "
        "line marks a failed run. Judge the returned code by step 6.",
        f"5. Price: $0.035 per agent minute ({PRICING_URL}); idle time and builds on your machine are not charged. "
        "The `--limit` option sets an agent-minute budget. Record the minutes you used.",
        "6. Referee the result. AWS Transform will have written Python into the repository; copy the one file "
        "that defines `compute` out as `logic.py` (it must be one self-contained file):",
        "",
        "   ```",
        "   ghost challenge <workbook> --code logic.py --mapping mapping.yaml --out <new-empty-folder>",
        "   ghost receipt <workbook> --kit . --definition " + shlex.quote(definition) + " --log <path-to-the-conversation-log> --out <another-new-empty-folder>",
        "   ```",
        "",
        "   `ghost challenge` runs the candidate's code on your machine, and a candidate that loops will hang it. "
        "Exit 0: no difference found on N cases. Exit 1: a difference, with a counterexample and a repair brief. "
        "Exit 2: it could not be refereed.",
        "",
        "## What the check does not show",
        "",
        "- The Referee is LibreOffice's recalculation of the workbook. Nothing is checked in Excel.",
        "- A pass does not extend to code that is trying to defeat the check: the candidate runs in the verifier's "
        "own process, with no sandbox.",
        "- `mapping.yaml` was derived from the workbook; a person has not confirmed it unless you did.",
        "- Recorded Decisions are not consulted by `ghost challenge`.",
        "",
    ]
    return "\n".join(lines)


def write_kit(workbook: str | Path, out: str | Path, definition: str | None = None) -> KitResult:
    """Write the kit into ``out`` (new or empty). Reads the workbook statically; runs nothing."""
    workbook, out = Path(workbook), Path(out)
    if not workbook.is_file():
        raise HandoffError(f"workbook not found: {workbook}")
    if not str(workbook).lower().endswith(ACCEPTED_FORMATS):
        raise HandoffError("unsupported file type. Accepted formats: .xlsx and .xlsm.")
    if out.exists() and (not out.is_dir() or any(out.iterdir())):
        raise HandoffError(f"--out {out} exists and is not an empty folder")
    thresholds = _thresholds()
    definition = definition or thresholds.transform_definition or DEFAULT_DEFINITION
    sizes = scan_sizes(workbook)
    over = _over(sizes)
    modules, vba_error = _read_vba(workbook)
    files: dict[str, str] = {}
    mapping = None
    if over:
        route = route_for_sizes(sizes, thresholds)
    else:
        from ghost import cli
        from ghost.autopsy.metrics import metrics as compute_metrics
        from ghost.converter.mapping import generate_mapping
        from ghost.router.route import recommend_route
        from ghost.rules.spec_writer import render_rules_md

        a = cli._analyse(workbook)
        mapping = generate_mapping(a.wb, a.roles)  # type: ignore[arg-type]
        files["rules.md"] = render_rules_md(a.rules)
        route = recommend_route(compute_metrics(a.wb), 1, thresholds)
    if modules:
        for name, source in module_files(modules):
            files[f"vba/{name}"] = source.rstrip("\n") + "\n"
    elif vba_error:
        files["vba/README.txt"] = f"The VBA project could not be read ({vba_error}). VBA: not readable.\n"
    else:
        files["vba/README.txt"] = "This workbook has no VBA project.\n"
    files["GHOST_CONTRACT.md"] = _contract(mapping, bool(modules) or bool(vba_error) or sizes.vba_present, mapping is not None)
    files["excel-semantics.md"] = _semantics_text()
    files[CONFIG_FILE] = (
        "# The -g file for `atx custom def exec`. Written by ghost handoff; nothing has been run with it.\n"
        "additionalPlanContext: |\n"
        "  Read GHOST_CONTRACT.md in this repository first. Migrate the VBA in vba/ to Python.\n"
        "  Produce one self-contained file named logic.py that defines compute(inputs) -> dict, with the\n"
        "  input and output names in mapping.yaml, following the contract exactly (Decimal arithmetic, Excel\n"
        "  ROUND, Excel error values). Keep the original behaviour, including its quirks; do not tidy them.\n"
    )
    reasons = list(route.reasons)
    files["RUN.md"] = _run_md(definition, sizes, [n for n, _ in module_files(modules)], vba_error, route,
                              mapping is not None, reasons)
    if mapping is not None:
        from ghost.converter.mapping import write_mapping
        out.mkdir(parents=True, exist_ok=True)
        write_mapping(mapping, out / "mapping.yaml")
    for rel, text in sorted(files.items()):
        p = out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
    names = sorted(str(p.relative_to(out)) for p in out.rglob("*") if p.is_file())
    return KitResult(names, mapping is not None, len(modules), vba_error, route.route)
