def _add_mapping_flags(p: argparse.ArgumentParser, with_file: bool = False) -> None:
    p.add_argument("--inputs", help="comma-separated input cells (Sheet!A1,...); overrides the proposed inputs")
    p.add_argument("--outputs", help="comma-separated output cells (Sheet!A1,...); overrides the proposed outputs")
    if with_file:
        p.add_argument("--mapping", help="use this mapping.yaml (confirmed inputs and outputs)")


def _add_verify_flags(p: argparse.ArgumentParser) -> None:
    p.add_argument("migration_dir", help="migration directory (.kiro/specs/<migration>)")
    p.add_argument("--mode", choices=["auto", "faithful", "intended", "both"], default="auto")
    p.add_argument("--workbook", help="source workbook (default: from source.yaml)")
    p.add_argument("--seed", type=int, default=DEFAULT_SEED)
    p.add_argument("--cases", type=int, default=DEFAULT_CASES)
    p.add_argument(
        "--trust-macros", action="store_true",
        help="allow macros in the Referee for this local, trusted file",
    )


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="ghost", description="Ghost in the Macro")
    sub = p.add_subparsers(dest="command", required=True)

    s = sub.add_parser("autopsy", help="analyse a workbook (read-only)")
    s.add_argument("workbook")
    _add_mapping_flags(s)
    s.set_defaults(func=cmd_autopsy)

    s = sub.add_parser("rules", help="write rules.md, traceability.yaml, findings.yaml")
    s.add_argument("workbook")
    s.add_argument("--migration", help="migration directory (default .kiro/specs/<name>)")
    _add_mapping_flags(s)
    s.set_defaults(func=cmd_rules)

    s = sub.add_parser("convert", help="write mapping.yaml and logic.py")
    s.add_argument("workbook")
    s.add_argument("--migration", help="migration directory (default .kiro/specs/<name>)")
    _add_mapping_flags(s, with_file=True)
    s.set_defaults(func=cmd_convert)

    s = sub.add_parser("verify", help="verify logic.py against the Referee and write proof reports")
    _add_verify_flags(s)
    s.set_defaults(func=cmd_verify)

    s = sub.add_parser("report", help="regenerate proof reports for a migration")
    _add_verify_flags(s)
    s.set_defaults(func=cmd_report)

    s = sub.add_parser("decide", help="record a human Decision")
    s.add_argument("migration_dir")
    g = s.add_mutually_exclusive_group()
    g.add_argument("--finding", help="Finding id, e.g. F-001")
    g.add_argument("--rule", help="Rule id, e.g. R-1a2b3c4d")
    s.add_argument("--behaviour", required=True)
    s.add_argument("--reason", required=True)
    s.add_argument("--author", required=True)
    s.add_argument("--date", help="ISO date (default today)")
    s.add_argument("--patch", help="Intended-mode patch as JSON")
    s.add_argument(
        "--set-operator", nargs=3, metavar=("CELL", "FROM", "TO"),
        help="patch: change a comparison operator in CELL from FROM to TO",
    )
    s.set_defaults(func=cmd_decide)

    s = sub.add_parser("mutate", help="mutation self-check of the verifier; adds the score to the report")
    _add_verify_flags(s)
    s.add_argument(
        "--mutant-cases", type=int, default=DEFAULT_MUTANT_CASES,
        help="cases per Mutant (plus targeted boundary cases)",
    )
    s.set_defaults(func=cmd_mutate)

    s = sub.add_parser("route", help="recommend a migration route (dry-run only)")
    s.add_argument("target", help="workbook path")
    s.add_argument("--batch-size", type=int, default=1)
    s.add_argument("--migration-dir", help="write the explanation into its design.md")
    s.set_defaults(func=cmd_route)

    s = sub.add_parser("demo", help="run the full flow on samples (a) and (b)")
    s.add_argument("--out", default="demo-out")
    s.add_argument("--seed", type=int, default=DEFAULT_SEED)
    s.add_argument("--cases", type=int, default=DEFAULT_CASES)
    s.set_defaults(func=cmd_demo)
    return p


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return int(args.func(args))
    except CliError as exc:
        print(f"ghost: error: {exc}", file=sys.stderr)
    except IngestError as exc:
        print(f"ghost: error: {type(exc).__name__}: {exc}", file=sys.stderr)
    except RefereeUnavailable as exc:
        print(f"ghost: error: Referee unavailable: {exc}", file=sys.stderr)
    except RefereeError as exc:
        print(f"ghost: error: Referee failed: {exc}", file=sys.stderr)
    except InvalidDecision as exc:
        print(f"ghost: error: invalid Decision: {exc}", file=sys.stderr)
    except InvalidPatch as exc:
        print(f"ghost: error: invalid Decision patch: {exc}", file=sys.stderr)
    except ReportValidationError as exc:
        print(f"ghost: error: proof report failed schema validation: {exc}", file=sys.stderr)
    except OSError as exc:
        print(f"ghost: error: {exc}", file=sys.stderr)
    return EXIT_FAIL


if __name__ == "__main__":
    raise SystemExit(main())
