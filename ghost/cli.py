def _default_migration(workbook: str | Path) -> Path:
    return Path(".kiro") / "specs" / Path(workbook).stem


def _write_source(mdir: Path, workbook: Path) -> None:
    mdir.mkdir(parents=True, exist_ok=True)
    wb_path = workbook.resolve()
    try:
        shown = os.path.relpath(wb_path, mdir.resolve())
    except ValueError:  # different drive
        shown = str(wb_path)
    (mdir / SOURCE_FILE).write_text(
        yaml.safe_dump({"workbook": shown}, sort_keys=False), encoding="utf-8"
    )


def _read_source(mdir: Path, override: str | None) -> Path:
    if override:
        return Path(override)
    src = mdir / SOURCE_FILE
    if not src.is_file():
        raise CliError(
            f"{src} not found. Run 'ghost rules <workbook> --migration {mdir}' first "
            "or pass --workbook."
        )
    data = yaml.safe_load(src.read_text(encoding="utf-8")) or {}
    name = data.get("workbook")
    if not name:
        raise CliError(f"{src} has no 'workbook' entry")
    p = Path(name)
    return p if p.is_absolute() else (mdir / p).resolve()


def _require_dir(path: str) -> Path:
    p = Path(path)
    if not p.is_dir():
        raise CliError(f"migration directory not found: {p}")
    return p


def _write_if_changed(path: Path, text: str) -> None:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, encoding="utf-8", newline="\n")


