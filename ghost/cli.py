def _load_sample_builder(module: str):
    root = Path(__file__).resolve().parent.parent / "samples"
    path = root / f"{module}.py"
    if not path.is_file():
        raise CliError(f"sample generator not found: {path}")
    sys.path.insert(0, str(root))
    try:
        spec = importlib.util.spec_from_file_location(module, path)
        assert spec and spec.loader
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
    finally:
        sys.path.remove(str(root))
    return mod.build


def cmd_demo(args: argparse.Namespace) -> int:
    out = Path(args.out)
    # Explicit mapping: the bulk threshold and delivery parameters (E2:E7) are
    # fixed parameters, so the counterexample varies only the three user inputs.
    demo_inputs = "Calculator!B2,Calculator!B3,Calculator!B4"
    demo_outputs = "Calculator!B11"
    samples = [("discount", "make_discount"), ("haunted", "make_haunted")]
    all_ok = True
    for name, module in samples:
        print(f"== Sample {name} (generated by samples/{module}.py) ==")
        xlsx = _load_sample_builder(module)(out / "samples" / f"{name}.xlsx")
        mdir = out / name
        if (mdir / SOURCE_FILE).is_file():  # rebuild a previous demo run from scratch
            shutil.rmtree(mdir)
        ns = argparse.Namespace(
            workbook=str(xlsx), migration=str(mdir), inputs=demo_inputs,
            outputs=demo_outputs, mapping=None,
        )
        cmd_autopsy(
            argparse.Namespace(workbook=str(xlsx), inputs=demo_inputs, outputs=demo_outputs)
        )
        cmd_rules(ns)
        cmd_convert(ns)
        a = _analyse(xlsx, demo_inputs, demo_outputs)
        for f in a.findings:
            frm_to = [(loc, op) for loc, op in f.locations if op == ">" and loc.cell]
            if not frm_to:
                continue
            loc, _ = frm_to[0]
            d = record(
                mdir,
                {
                    "finding_id": f.finding_id,
                    "behaviour": "Bulk means 50 or more: free delivery applies at quantity >= 50",
                    "reason": "Discount and delivery must agree on the bulk threshold",
                    "author": "demo",
                    "date": DEMO_DATE,
                    "patch": {"op": "set_operator", "cell": loc.cell, "from": ">", "to": ">="},
                },
            )
            print(f"Recorded {d.decision_id} for {f.finding_id}")
        ok = run_verification(mdir, mode="auto", seed=args.seed, cases=args.cases)
        all_ok = all_ok and ok
    if not all_ok:
        print("ghost: demo failed: a sample did not verify as expected", file=sys.stderr)
        return EXIT_FAIL
    return 0


