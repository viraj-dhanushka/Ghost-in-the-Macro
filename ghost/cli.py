def cmd_decide(args: argparse.Namespace) -> int:
    mdir = _require_dir(args.migration_dir)
    patch: dict[str, Any] = {}
    if args.patch:
        try:
            patch = json.loads(args.patch)
        except json.JSONDecodeError as exc:
            raise CliError(f"--patch is not valid JSON: {exc}") from exc
    if args.set_operator:
        cell, frm, to = args.set_operator
        patch = {"op": "set_operator", "cell": cell, "from": frm, "to": to}
    d = record(
        mdir,
        {
            "finding_id": args.finding,
            "rule_id": args.rule,
            "behaviour": args.behaviour,
            "reason": args.reason,
            "author": args.author,
            "date": args.date or date.today().isoformat(),
            "patch": patch,
        },
    )
    print(f"Recorded {d.decision_id} in {mdir / 'decisions.yaml'}")
    return 0


