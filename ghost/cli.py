def _is_generated(path: Path) -> bool:
    return path.is_file() and path.read_text(encoding="utf-8").startswith(GENERATED_MARK)


def _resolve_mapping(
    a: Analysis, mdir: Path, args: argparse.Namespace
) -> Mapping:
    """--mapping wins, then explicit --inputs/--outputs, then an existing mapping.yaml."""
    target = mdir / MAPPING_FILE
    if args.mapping:
        src = Path(args.mapping)
        if not src.is_file():
            raise CliError(f"--mapping file not found: {src}")
        mapping = read_mapping(src)
        for name, spec in {**mapping.inputs, **mapping.outputs}.items():
            if spec.cell not in a.wb.cells:
                raise CliError(f"--mapping: {name} points at {spec.cell}, not in the workbook")
        write_mapping(mapping, target)
        return mapping
    if args.inputs or args.outputs or not target.is_file():
        mapping = generate_mapping(a.wb, a.roles)  # type: ignore[arg-type]
        write_mapping(mapping, target)
        return mapping
    return read_mapping(target)


def _emit_logic(wb: Workbook, mapping: Mapping, mode: str, decisions: list) -> tuple[str, list]:
    try:
        res = emit_module(wb, mapping, mode, decisions)
    except InvalidPatch as exc:
        raise CliError(f"Decision patch cannot be applied: {exc}") from exc
    return res.code, list(res.not_converted)


def _copy_runtime(mdir: Path) -> None:
    import ghost.runtime.excel as rt

    shutil.copyfile(rt.__file__, mdir / "excel.py")


def cmd_convert(args: argparse.Namespace) -> int:
    a = _analyse(args.workbook, args.inputs, args.outputs)
    mdir = Path(args.migration) if args.migration else _default_migration(args.workbook)
    mdir.mkdir(parents=True, exist_ok=True)
    _write_source(mdir, Path(args.workbook))
    mapping = _resolve_mapping(a, mdir, args)
    decisions = load_decisions(mdir)
    code, nc = _emit_logic(a.wb, mapping, "faithful", decisions)
    (mdir / LOGIC_FILE).write_text(code, encoding="utf-8", newline="\n")
    _copy_runtime(mdir)
    print(f"Wrote {mdir / MAPPING_FILE} ({len(mapping.inputs)} inputs, {len(mapping.outputs)} outputs)")
    print(f"Wrote {mdir / LOGIC_FILE} (faithful)")
    if any(d.patch for d in decisions):
        icode, _ = _emit_logic(a.wb, mapping, "intended", decisions)
        (mdir / "logic_intended.py").write_text(icode, encoding="utf-8", newline="\n")
        print(f"Wrote {mdir / 'logic_intended.py'} (intended, {len(decisions)} decision(s))")
    if nc:
        print("Not converted:")
        for e in nc:
            print(f"  {e.cell}: {e.reason}")
    return 0


