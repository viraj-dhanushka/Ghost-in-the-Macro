def cmd_mutate(args: argparse.Namespace) -> int:
    """Verify, run the mutation self-check, and write proof reports that include it."""
    mdir = _require_dir(args.migration_dir)
    ok = run_verification(
        mdir, mode=args.mode, workbook=args.workbook, trust_macros=args.trust_macros,
        seed=args.seed, cases=args.cases, mutation_cases=args.mutant_cases,
    )
    if not ok:
        print("ghost: verification failed: mismatches not explained by a Decision", file=sys.stderr)
        return EXIT_FAIL
    return 0


def cmd_route(args: argparse.Namespace) -> int:
    from ghost.router import (
        ThresholdError,
        recommend_route,
        with_atx_command,
        write_route_explanation,
    )

    wb = _load(args.target)
    try:
        route = with_atx_command(
            recommend_route(compute_metrics(wb), args.batch_size), args.target
        )
    except ThresholdError as exc:
        raise CliError(f"routing thresholds: {exc}") from exc
    print(f"Route: {route.route}")
    for reason in route.reasons:
        print(f"  - {reason}")
    if route.atx_command:
        print("Dry run (not executed):")
        print(f"  {route.atx_command}")
    if args.migration_dir:
        print(f"Wrote route explanation to {write_route_explanation(args.migration_dir, route)}")
    return 0


