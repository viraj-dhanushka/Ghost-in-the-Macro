def _load(path: str | Path) -> Workbook:
    p = Path(path)
    if not p.is_file():
        raise CliError(f"workbook not found: {p}")
    wb = load_workbook(str(p))
    wb.features = scan_features(wb)
    if p.suffix.lower() == ".xlsm":
        wb.vba_modules = extract_vba(p)  # static read, nothing is executed
    return wb


def _qualify_cells(wb: Workbook, text: str | None, flag: str) -> list[str]:
    if not text:
        return []
    out: list[str] = []
    for raw in text.split(","):
        ref = raw.strip().replace("$", "")
        if not ref:
            continue
        if "!" not in ref:
            if len(wb.sheets) != 1:
                raise CliError(f"{flag}: '{ref}' needs a sheet name (Sheet!A1)")
            ref = f"{wb.sheets[0]}!{ref}"
        ref = ref.replace("'", "")
        if ref not in wb.cells:
            raise CliError(f"{flag}: cell {ref} is not in the workbook")
        out.append(ref)
    return out


@dataclass
class Analysis:
    wb: Workbook
    roles: dict[str, str]
    thresholds: list[Threshold]
    findings: list[Finding]
    rules: list[Rule]


def _apply_overrides(
    wb: Workbook, roles: dict[str, str], inputs: list[str], outputs: list[str]
) -> dict[str, str]:
    """User-confirmed mapping: explicit cells win over the proposed roles."""
    roles = dict(roles)
    if outputs:
        for ref, role in list(roles.items()):
            if role == "OUTPUT" and ref not in outputs:
                roles[ref] = "INTERMEDIATE"
        for ref in outputs:
            roles[ref] = "OUTPUT"
    if inputs:
        for ref, role in list(roles.items()):
            if role == "INPUT" and ref not in inputs:
                roles[ref] = "PARAMETER"
        for ref in inputs:
            if wb.cells[ref].formula is not None:
                raise CliError(f"--inputs: {ref} holds a formula, not a constant")
            roles[ref] = "INPUT"
    return roles


def _analyse(path: str | Path, inputs: str | None = None, outputs: str | None = None) -> Analysis:
    wb = _load(path)
    outs = _qualify_cells(wb, outputs, "--outputs")
    ins = _qualify_cells(wb, inputs, "--inputs")
    roles = _apply_overrides(wb, dict(classify(wb, outs)), ins, outs)
    thresholds = extract_thresholds(wb)
    findings = detect_inconsistencies(thresholds)
    rules = generate_rules(wb, roles, thresholds)
    return Analysis(wb, roles, thresholds, findings, rules)  # type: ignore[arg-type]


def _roles_from_mapping(mapping: Mapping) -> dict[str, str]:
    roles = {s.cell: "INPUT" for s in mapping.inputs.values()}
    roles.update({s.cell: "OUTPUT" for s in mapping.outputs.values()})
    return roles


