"""Ghost command line: ``python -m ghost.cli <command>``.

Commands: autopsy, rules, convert, verify, mutate, report, decide, route, demo.

The CLI holds no business logic. It loads inputs, calls the engine
(``ghost.ingest``, ``ghost.autopsy``, ``ghost.rules``, ``ghost.converter``,
``ghost.verifier``, ``ghost.referee``, ``ghost.report``, ``ghost.decisions``)
and prints what the engine returned. Every failure exits non-zero with a
message that names the cause (Requirement 11.4).

Migration directory (``.kiro/specs/<migration>/``) written by these commands:
``rules.md``, ``traceability.yaml``, ``findings.yaml``, ``decisions.yaml``,
``design.md``, ``mapping.yaml``, ``logic.py`` (+ ``excel.py`` runtime),
``source.yaml`` (path of the source workbook) and ``reports/<mode>/`` with the
proof report per mode. ``proof-report.{json,html}`` in the migration directory
is a copy of the most relevant mode (Intended when Decisions exist).

Requirements: 11.1, 11.2, 11.4.
"""
