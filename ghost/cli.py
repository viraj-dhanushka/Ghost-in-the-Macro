def _soffice_version(soffice: str) -> str | None:
    try:
        out = subprocess.run(
            [soffice, "--version"], capture_output=True, text=True, timeout=30
        ).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None
    return out or None


def _accepts_trace(compute) -> bool:
    try:
        params = inspect.signature(compute).parameters
    except (TypeError, ValueError):
        return False
    return len(params) >= 2 or any(p.kind == p.VAR_KEYWORD for p in params.values())


def _base_inputs(wb: Workbook, mapping: Mapping) -> dict[str, Any]:
    base: dict[str, Any] = {}
    for name, spec in mapping.inputs.items():
        v = wb.cells[spec.cell].value if spec.cell in wb.cells else None
        if isinstance(v, float):
            v = Decimal(repr(v))
        base[name] = v
    return base


def _probe_boundaries(
    referee: RefereeClient, wb: Workbook, mapping: Mapping, thresholds: list[Threshold]
) -> list[BoundaryResult]:
    cell_to_name = {s.cell: n for n, s in mapping.inputs.items()}
    wire_base = {s.cell: wb.cells[s.cell].value for s in mapping.inputs.values() if s.cell in wb.cells}
    done: set[tuple] = set()
    results: list[BoundaryResult] = []
    for t in sorted(thresholds, key=lambda t: (t.cell, t.constant, t.source.cell or "")):
        name = cell_to_name.get(t.cell)
        out_cell = t.source.cell
        if name is None or out_cell is None:
            continue
        key = (t.cell, t.constant, out_cell)
        if key in done:
            continue
        done.add(key)
        spec = mapping.inputs[name]
        lo = t.constant - 10
        if spec.min is not None and lo < spec.min:
            lo = spec.min
        results.append(
            boundary_mod.probe(
                referee, wire_base, t.cell, out_cell, lo, t.constant + 10,
                threshold=t.constant, step=1,
            )
        )
    return results


def _modes_to_run(requested: str, decisions: list, transpiled: bool) -> list[str]:
    if requested == "both":
        return ["faithful", "intended"]
    if requested in ("faithful", "intended"):
        return [requested]
    return ["faithful", "intended"] if decisions and transpiled else ["faithful"]


def _module_source(
    mdir: Path, mode: str, wb: Workbook, mapping: Mapping, decisions: list
) -> tuple[str, str]:
    """Return (source, origin). Transpiler output is regenerated; other code is used as written."""
    logic = mdir / LOGIC_FILE
    if logic.is_file() and not _is_generated(logic):
        return logic.read_text(encoding="utf-8"), str(logic)
    code, _ = _emit_logic(wb, mapping, mode, decisions)
    if mode == "faithful":
        _write_if_changed(logic, code)
        _copy_runtime(mdir)
        return code, str(logic)
    path = mdir / "logic_intended.py"
    _write_if_changed(path, code)
    return code, str(path)


def _print_result(mode: str, res, report) -> None:
    status = "PASS" if res.passed else "FAIL"
    print(f"[{mode}] {status}: {res.cases_tested} cases, {len(res.mismatches)} mismatch(es), seed {res.seed}")
    for m in res.mismatches:
        ins = ", ".join(f"{k}={v}" for k, v in sorted(m.case.inputs.items()))
        extra = f" {m.finding_id or ''} {m.decision_id or ''}".rstrip()
        print(
            f"    {m.output} ({m.cell}): referee={m.case.referee.get(m.output)!r} "
            f"actual={m.case.actual.get(m.output)!r}  inputs: {ins}"
        )
        print(f"    class: {m.mismatch_class}{(' ' + extra) if extra.strip() else ''}")
    for b in report.boundaries:
        if b.change_point is not None:
            print(
                f"    boundary {b.cell}: {b.input_name} changes at {b.change_point}"
                f" (threshold {b.threshold}, {b.operator_includes or 'off-threshold'})"
            )
    unc = [c for c in report.rule_coverage if c.uncovered]
    if unc:
        print(f"    uncovered conditions: {', '.join(c.condition_id for c in unc)}")
    s = report.sanity
    print(f"    Excel cross-check: {getattr(s, 'status', 'not checked')}")


def run_verification(
    mdir: Path,
    *,
    mode: str = "auto",
    workbook: str | None = None,
    trust_macros: bool = False,
    seed: int = DEFAULT_SEED,
    cases: int = DEFAULT_CASES,
    mutation_cases: int = 0,
) -> bool:
    """Verify a migration against the Referee in the requested modes and write proof reports.

    ``mutation_cases`` > 0 also runs the mutation self-check (that many cases
    per Mutant) and includes the result in the report; 0 leaves it "not checked".
    """
    wb_path = _read_source(mdir, workbook)
    wb = _load(wb_path)
    mapping_file = mdir / MAPPING_FILE
    if not mapping_file.is_file():
        raise CliError(f"{mapping_file} not found. Run 'ghost convert' first.")
    mapping = read_mapping(mapping_file)
    if not mapping.outputs:
        raise CliError(f"{mapping_file} has no outputs to verify")
    thresholds = extract_thresholds(wb)
    findings = detect_inconsistencies(thresholds)
    rules = generate_rules(wb, _roles_from_mapping(mapping), thresholds)  # type: ignore[arg-type]
    decisions = load_decisions(mdir)
    logic = mdir / LOGIC_FILE
    transpiled = not logic.is_file() or _is_generated(logic)
    modes = _modes_to_run(mode, decisions, transpiled)
    soffice = locate_soffice()
    lo_version = _soffice_version(soffice)
    constants = [t.constant for t in thresholds]
    base = _base_inputs(wb, mapping)
    ok = True
    reports: dict[str, Path] = {}
    with RefereeClient(
        soffice, wb_path, run_macros=trust_macros, trusted_source=trust_macros
    ) as referee:
        sanity = run_sanity(wb, referee)
        boundaries = _probe_boundaries(referee, wb, mapping, thresholds)
        # The mutation self-check judges the Faithful module, where the
        # unmutated baseline must have zero Mismatches; the result is shared
        # by every mode's report.
        mutation = None  # build_report turns None into "not checked"
        if mutation_cases:
            fsource, _ = _module_source(mdir, "faithful", wb, mapping, decisions)
            fcfg = VerifyConfig(seed=seed, max_examples=cases, thresholds=thresholds)
            try:
                mutation = run_mutation(
                    fsource, mapping, referee, fcfg, cases=mutation_cases,
                    targeted=list(candidate_inputs(base, constants)),
                )
            except MutationBaselineFailed as exc:
                print(f"mutation check: not checked ({exc})")
        for m in modes:
            source, origin = _module_source(mdir, m, wb, mapping, decisions)
            compute = load_compute(source)
            tracker = CoverageTracker(rules)
            traced = _accepts_trace(compute)
            cfg = VerifyConfig(
                seed=seed,
                max_examples=cases,
                mode=m,  # type: ignore[arg-type]
                thresholds=thresholds,
                trace=tracker.trace if traced else None,
                classifier=make_classifier(m, findings, decisions, rules, wb.deps),  # type: ignore[arg-type]
            )
            res = verify(compute, mapping, referee, cfg)
            if traced:
                close_gaps(tracker, compute, candidate_inputs(base, constants))
            report = build_report(
                seed=res.seed,
                mode=m,
                cases_tested=res.cases_tested,
                passed=res.passed,
                mismatches=res.mismatches,
                boundaries=boundaries,
                rule_coverage=tracker.report() if traced else [],
                mutation=mutation,
                sanity=sanity,
                findings=findings,
                decisions=decisions,
                libreoffice_version=lo_version,
            )
            out = mdir / "reports" / m
            write_report(report, out)
            reports[m] = out
            _print_result(m, res, report)
            if mutation is not None:
                for line in describe_mutation(mutation):
                    print(f"    {line}")
            print(f"    module: {origin}")
            print(f"    report: {out / REPORT_HTML}")
            ok = ok and res.passed
    primary = reports.get("intended") or reports["faithful"]
    for name in (REPORT_JSON, REPORT_HTML):
        shutil.copyfile(primary / name, mdir / name)
    print(f"Proof report: {mdir / REPORT_HTML}")
    return ok


def cmd_verify(args: argparse.Namespace) -> int:
    mdir = _require_dir(args.migration_dir)
    ok = run_verification(
        mdir, mode=args.mode, workbook=args.workbook, trust_macros=args.trust_macros,
        seed=args.seed, cases=args.cases,
    )
    if not ok:
        print("ghost: verification failed: mismatches not explained by a Decision", file=sys.stderr)
        return EXIT_FAIL
    return 0


def cmd_report(args: argparse.Namespace) -> int:
    """Regenerate proof reports from engine output (re-runs verification)."""
    return cmd_verify(args)


