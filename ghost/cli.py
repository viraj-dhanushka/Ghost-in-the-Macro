def cmd_autopsy(args: argparse.Namespace) -> int:
    a = _analyse(args.workbook, args.inputs, args.outputs)
    wb = a.wb
    m = compute_metrics(wb)
    print(f"Autopsy: {args.workbook}")
    print(f"  sheets: {', '.join(wb.sheets)}")
    print(
        f"  formulas: {m.formula_count}  VBA lines: {m.vba_line_count}  "
        f"modules: {m.module_count}  calculator shape: {'yes' if m.calculator_shape else 'no'}"
    )
    print(
        "  Excel-saved values: "
        + ("present" if wb.excel_saved else "none (will report 'not cross-checked against Excel')")
    )
    for role in ("INPUT", "OUTPUT"):
        cells = [r for r, v in sorted(a.roles.items()) if v == role]
        print(f"  {role.lower()}s ({len(cells)}): {', '.join(cells) or 'none'}")
    if a.thresholds:
        print("  thresholds:")
        for t in a.thresholds:
            where = t.source.cell or f"{t.source.module}:{t.source.line}"
            print(f"    {t.cell} {t.operator} {t.constant}  at {where}")
    if a.findings:
        print("  findings:")
        for f in a.findings:
            print(f"    {f.finding_id} operator conflict on {f.cell} vs {f.constant}:")
            for loc, op in f.locations:
                where = loc.cell or f"{loc.module}:{loc.line}"
                print(f"      {where} uses '{op}'")
    else:
        print("  findings: none")
    nc = find_not_converted(wb)
    if nc:
        print("  not converted:")
        for e in nc:
            print(f"    {e.cell}: {e.reason}")
    flagged = [f for f in wb.features if f.not_verifiable]
    if flagged:
        print("  not verifiable as-is (excluded from comparison):")
        for f in flagged:
            print(f"    {f.cell}: {f.kind} {f.detail}".rstrip())
    return 0


