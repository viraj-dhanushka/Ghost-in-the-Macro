"""Python emitter (Faithful mode, with Decision patches for Intended mode).

``emit_python(workbook, mapping, mode, decisions)`` returns the source of a
module exposing ``compute(inputs, trace=None) -> dict``. Output is a pure
function of its arguments: no timestamps, sorted iteration everywhere, so
identical input gives byte-identical output (Requirement 7.11).

Cells listed by ``find_not_converted`` (and cells the emitter itself cannot
translate) get no code. Outputs that depend on them are left out of the
result and named in the module header. Nothing is guessed (Requirement 7.7).

``trace(condition_id, bool)`` is called for each IF condition evaluated, with
ids of the form ``"Sheet!B7#1"`` (cell plus the 1-based IF index in the
formula, pre-order). The Verifier uses it for rule coverage.
"""

from __future__ import annotations

import dataclasses
from dataclasses import dataclass
from decimal import Decimal

from openpyxl.utils import column_index_from_string, get_column_letter

from ghost.converter.ast import (
    Ast,
    BinaryOp,
    Boolean,
    CellRef,
    ErrorLiteral,
    FuncCall,
    MissingArg,
    NameRef,
    Number,
    Percent,
    RangeRef,
    String,
    UnaryOp,
    walk,
)
from ghost.converter.names import substitute_names
from ghost.converter.parser import FormulaSyntaxError, parse_formula
from ghost.converter.subset import NotConverted, find_not_converted
from ghost.models import Decision, Mapping, Workbook

__all__ = ["EmitResult", "InvalidPatch", "emit_module", "emit_python"]

_MAX_RANGE_CELLS = 10_000

_HEADER = '''\
"""Generated by Ghost (Faithful logic). Do not edit by hand."""
from decimal import Decimal

try:  # imported as a package, vendored excel.py next to this file
    from .excel import *  # noqa: F401,F403
except ImportError:
    try:  # run from the module folder (python -c "import logic")
        from excel import *  # noqa: F401,F403
    except ImportError:  # running from the Ghost source tree
        from ghost.runtime.excel import *  # noqa: F401,F403


class _Rng:
    __slots__ = ("rows", "cols", "vals")

    def __init__(self, rows, cols, vals):
        self.rows, self.cols, self.vals = rows, cols, vals


def _inp(x):
    if x == "" and isinstance(x, str):
        return None  # the Referee stores "" as an empty cell
    if x is None or isinstance(x, (Decimal, str, bool, ExcelError)):
        return x
    if isinstance(x, (int, float)):
        return to_decimal(x)
    return x


def _flat(args):
    for a in args:
        if isinstance(a, _Rng):
            for x in a.vals:
                yield x, True
        else:
            yield a, False


def _nums(args):
    out = []
    for x, in_rng in _flat(args):
        if isinstance(x, ExcelError):
            return x
        if in_rng and (x is None or isinstance(x, (str, bool))):
            continue
        n = xl_num(x)
        if isinstance(n, ExcelError):
            return n
        out.append(n)
    return out


def _sum(*args):
    n = _nums(args)
    if isinstance(n, ExcelError):
        return n
    total = Decimal(0)
    for d in n:
        total = xl_add(total, d)
    return total


def _min(*args):
    n = _nums(args)
    if isinstance(n, ExcelError):
        return n
    return min(n) if n else Decimal(0)


def _max(*args):
    n = _nums(args)
    if isinstance(n, ExcelError):
        return n
    return max(n) if n else Decimal(0)


def _average(*args):
    n = _nums(args)
    if isinstance(n, ExcelError):
        return n
    if not n:
        return DIV0
    total = Decimal(0)
    for d in n:
        total = xl_add(total, d)
    return xl_div(total, Decimal(len(n)))


def _logic(args, is_and):
    vals = []
    for x, in_rng in _flat(args):
        if isinstance(x, ExcelError):
            return x
        if in_rng and (x is None or isinstance(x, str)):
            continue
        b = xl_bool(x)
        if isinstance(b, ExcelError):
            return b
        vals.append(b)
    if not vals:
        return VALUE
    return all(vals) if is_and else any(vals)


def _and(*args):
    return _logic(args, True)


def _or(*args):
    return _logic(args, False)


def _not(x):
    b = xl_bool(x)
    return b if isinstance(b, ExcelError) else (not b)


def _abs(x):
    n = xl_num(x)
    return n if isinstance(n, ExcelError) else abs(n)


def _if(trace, cid, cond, then, other):
    c = xl_bool(cond)
    if isinstance(c, ExcelError):
        return c
    if trace is not None:
        trace(cid, c)
    return then() if c else other()


def _iferror(value, fallback):
    r = value()
    return fallback() if isinstance(r, ExcelError) else r


def _choose(i, *options):
    n = xl_num(i)
    if isinstance(n, ExcelError):
        return n
    k = int(n)
    if k < 1 or k > len(options):
        return VALUE
    return options[k - 1]


def _index(rng, r=None, c=None):
    rn = xl_num(r)
    if isinstance(rn, ExcelError):
        return rn
    ri = int(rn)
    if c is None:
        if rng.rows == 1 and rng.cols > 1:
            ri, ci = 1, ri  # one row: the argument picks the column
        else:
            ci = 1
    else:
        cn = xl_num(c)
        if isinstance(cn, ExcelError):
            return cn
        ci = int(cn)
    # A 0 asks for a whole row or column. On a dimension of length 1 that is the
    # single row or column (LibreOffice, measured; Excel not verified); on a
    # longer dimension a single-cell formula cannot hold it (#VALUE!).
    if ri == 0:
        if rng.rows != 1:
            return VALUE
        ri = 1
    if ci == 0:
        if rng.cols != 1:
            return VALUE
        ci = 1
    if ri < 1 or ci < 1 or ri > rng.rows or ci > rng.cols:
        return REF
    v = rng.vals[(ri - 1) * rng.cols + (ci - 1)]
    return Decimal(0) if v is None else v
def _kind(x):
    if isinstance(x, bool):
        return 2
    if isinstance(x, str):
        return 1
    return 0


def _match(x, rng):
    if isinstance(x, ExcelError):
        return x
    if x is None or (rng.rows > 1 and rng.cols > 1):
        return NA
    for i, v in enumerate(rng.vals):
        if v is None or isinstance(v, ExcelError):
            continue
        if _kind(v) == _kind(x) and xl_compare(v, x) == 0:
            return Decimal(i + 1)
    return NA

'''


class _Unsupported(Exception):
    """Raised while translating a formula the emitter cannot convert."""


@dataclass(frozen=True)
class EmitResult:
    code: str
    not_converted: tuple[NotConverted, ...]
    omitted_outputs: tuple[str, ...]


_BINARY = {
    "+": "xl_add",
    "-": "xl_sub",
    "*": "xl_mul",
    "/": "xl_div",
    "^": "xl_pow",
    "&": "xl_concat",
    "=": "xl_eq",
    "<>": "xl_ne",
    "<": "xl_lt",
    "<=": "xl_le",
    ">": "xl_gt",
    ">=": "xl_ge",
}
_COMPARISONS = frozenset({"=", "<>", "<", "<=", ">", ">="})

# name -> (helper, min args, max args or None)
_SIMPLE = {
    "ROUND": ("xl_round", 2, 2),
    "ROUNDUP": ("xl_roundup", 2, 2),
    "ROUNDDOWN": ("xl_rounddown", 2, 2),
    "INT": ("xl_int", 1, 1),
    "MOD": ("xl_mod", 2, 2),
    "ABS": ("_abs", 1, 1),
    "NOT": ("_not", 1, 1),
    "CHOOSE": ("_choose", 2, None),
}
_AGGREGATES = {
    "SUM": "_sum",
    "MIN": "_min",
    "MAX": "_max",
    "AVERAGE": "_average",
    "AND": "_and",
    "OR": "_or",
}


def _key(sheet: str, address: str) -> str:
    return f"{sheet}!{address}"


def _norm(ref: str) -> str:
    return ref.replace("$", "")


def _sheet_of(cell: str) -> str:
    return cell.rsplit("!", 1)[0]


def _expand(rng: RangeRef, sheet: str) -> tuple[int, int, list[str]]:
    s = rng.start.sheet or sheet
    c1, c2 = sorted(
        (column_index_from_string(rng.start.col), column_index_from_string(rng.end.col))
    )
    r1, r2 = sorted((rng.start.row, rng.end.row))
    rows, cols = r2 - r1 + 1, c2 - c1 + 1
    if rows * cols > _MAX_RANGE_CELLS:
        raise _Unsupported(f"range larger than {_MAX_RANGE_CELLS} cells")
    keys = [
        _key(s, f"{get_column_letter(c)}{r}")
        for r in range(r1, r2 + 1)
        for c in range(c1, c2 + 1)
    ]
    return rows, cols, keys


def _refs(ast: Ast, sheet: str) -> set[str]:
    """Every cell key a formula reads."""
    out: set[str] = set()
    for node in walk(ast):
        if isinstance(node, CellRef):
            out.add(_key(node.sheet or sheet, node.address))
        elif isinstance(node, RangeRef):
            try:
                out.update(_expand(node, sheet)[2])
            except _Unsupported:
                pass  # reported by translation
    return out


# ---------------------------------------------------------------- patches


class InvalidPatch(ValueError):
    """A Decision patch Ghost cannot apply. Nothing is guessed."""


def _validate_patches(decisions: list[Decision]) -> None:
    for d in decisions:
        p = d.patch
        if not p:  # record-only Decision, no behaviour change to apply
            continue
        if p.get("op") != "set_operator":
            raise InvalidPatch(f"{d.decision_id}: unsupported patch op {p.get('op')!r}")
        if not p.get("cell"):
            raise InvalidPatch(f"{d.decision_id}: patch has no 'cell'")
        if p.get("to") not in _COMPARISONS:
            raise InvalidPatch(f"{d.decision_id}: invalid operator {p.get('to')!r}")
        if p.get("from") is not None and p["from"] not in _COMPARISONS:
            raise InvalidPatch(f"{d.decision_id}: invalid operator {p['from']!r}")


def _patch_ast(
    ast: Ast, cell: str, decisions: list[Decision], applied: set[str] | None = None
) -> Ast:
    """Apply ``set_operator`` patches targeting ``cell`` (Intended mode)."""
    for d in sorted(decisions, key=lambda d: d.decision_id):
        p = d.patch
        if p.get("op") != "set_operator":
            continue
        target = _norm(str(p.get("cell", "")))
        if target != cell and not cell.endswith("!" + target):
            continue
        to, frm = str(p["to"]), p.get("from")

        def rewrite(node, done):
            if done:
                return node, True
            if isinstance(node, BinaryOp):
                if node.op in _COMPARISONS and (frm is None or node.op == frm):
                    return dataclasses.replace(node, op=to), True
                left, done = rewrite(node.left, False)
                right, done = rewrite(node.right, done)
                return dataclasses.replace(node, left=left, right=right), done
            if isinstance(node, (UnaryOp, Percent)):
                inner, done = rewrite(node.operand, False)
                return dataclasses.replace(node, operand=inner), done
            if isinstance(node, FuncCall):
                args, flag = [], False
                for a in node.args:
                    a2, flag = rewrite(a, flag)
                    args.append(a2)
                return dataclasses.replace(node, args=tuple(args)), flag
            return node, False

        ast, hit = rewrite(ast, False)
        if hit and applied is not None:
            applied.add(d.decision_id)
    return ast


# ------------------------------------------------------------- translation


class _Translator:
    def __init__(self, cell: str):
        self.cell = cell
        self.sheet = _sheet_of(cell)
        self.if_count = 0

    def ref(self, node: CellRef) -> str:
        return f"v[{_key(node.sheet or self.sheet, node.address)!r}]"

    def range_arg(self, node: Ast) -> str:
        if isinstance(node, CellRef):
            return f"_Rng(1, 1, [{self.ref(node)}])"
        if isinstance(node, RangeRef):
            rows, cols, keys = _expand(node, self.sheet)
            cells = ", ".join(f"v[{k!r}]" for k in keys)
            return f"_Rng({rows}, {cols}, [{cells}])"
        raise _Unsupported("a range or cell reference is required here")

    def scalar(self, node: Ast) -> str:
        if isinstance(node, Number):
            return f"Decimal({str(node.value)!r})"
        if isinstance(node, String):
            return repr(node.value)
        if isinstance(node, Boolean):
            return repr(node.value)
        if isinstance(node, ErrorLiteral):
            return f"ExcelError({node.code!r})"
        if isinstance(node, MissingArg):
            return "Decimal(0)"
        if isinstance(node, CellRef):
            return self.ref(node)
        if isinstance(node, RangeRef):
            raise _Unsupported("range used where a single value is expected")
        if isinstance(node, NameRef):
            raise _Unsupported(f"named reference {node.name} is not supported")
        if isinstance(node, UnaryOp):
            inner = self.scalar(node.operand)
            return f"xl_neg({inner})" if node.op == "-" else inner
        if isinstance(node, Percent):
            return f"xl_percent({self.scalar(node.operand)})"
        if isinstance(node, BinaryOp):
            fn = _BINARY.get(node.op)
            if fn is None:
                raise _Unsupported(f"operator {node.op} is outside the P0 subset")
            return f"{fn}({self.scalar(node.left)}, {self.scalar(node.right)})"
        if isinstance(node, FuncCall):
            return self.call(node)
        raise _Unsupported(f"unsupported node {type(node).__name__}")

    def call(self, node: FuncCall) -> str:
        name, args = node.name, node.args
        n = len(args)
        if name == "IF":
            if n not in (2, 3):
                raise _Unsupported("IF needs 2 or 3 arguments")
            self.if_count += 1
            cid = f"{self.cell}#{self.if_count}"
            cond = self.scalar(args[0])
            then = self.scalar(args[1])
            other = self.scalar(args[2]) if n == 3 else "False"
            return f"_if(trace, {cid!r}, {cond}, lambda: {then}, lambda: {other})"
        if name == "IFERROR":
            if n != 2:
                raise _Unsupported("IFERROR needs 2 arguments")
            return f"_iferror(lambda: {self.scalar(args[0])}, lambda: {self.scalar(args[1])})"
        if name in _SIMPLE:
            fn, lo, hi = _SIMPLE[name]
            if n < lo or (hi is not None and n > hi):
                raise _Unsupported(f"{name} called with {n} arguments")
            return f"{fn}({', '.join(self.scalar(a) for a in args)})"
        if name in _AGGREGATES:
            if n < 1:
                raise _Unsupported(f"{name} needs at least one argument")
            parts = [
                self.range_arg(a) if isinstance(a, (CellRef, RangeRef)) else self.scalar(a)
                for a in args
            ]
            return f"{_AGGREGATES[name]}({', '.join(parts)})"
        if name == "INDEX":
            if n not in (2, 3):
                raise _Unsupported("INDEX needs 2 or 3 arguments")
            rest = [self.scalar(a) for a in args[1:]]
            return f"_index({self.range_arg(args[0])}, {', '.join(rest)})"
        if name == "MATCH":
            exact = n == 3 and (
                (isinstance(args[2], Number) and args[2].value == 0)
                or (isinstance(args[2], Boolean) and args[2].value is False)
            )
            if not exact:
                raise _Unsupported("only exact-match MATCH (match_type 0) is supported")
            return f"_match({self.scalar(args[0])}, {self.range_arg(args[1])})"
        raise _Unsupported(f"function {name} is outside the P0 subset")


# ------------------------------------------------------------------ emit


def _const_code(value: object) -> str:
    if value is None or isinstance(value, (bool, str)):
        return repr(value)
    if isinstance(value, Decimal):
        return f"Decimal({str(value)!r})"
    if isinstance(value, float):
        return f"Decimal({str(Decimal(repr(value)))!r})"
    if isinstance(value, int):
        return f"Decimal({str(value)!r})"
    return repr(str(value))


def emit_module(
    workbook: Workbook,
    mapping: Mapping,
    mode: str = "faithful",
    decisions: list[Decision] | None = None,
) -> EmitResult:
    """Generate the module source plus the not-converted listing."""
    if mode not in ("faithful", "intended"):
        raise ValueError(f"unknown mode {mode!r}")
    patches = list(decisions or []) if mode == "intended" else []
    _validate_patches(patches)
    applied: set[str] = set()

    in_cells = {name: _norm(spec.cell) for name, spec in mapping.inputs.items()}
    input_cells = set(in_cells.values())

    not_converted: list[NotConverted] = list(find_not_converted(workbook))
    bad: set[str] = {e.cell for e in not_converted if e.cell}

    code: dict[str, str] = {}
    deps: dict[str, set[str]] = {}
    for cell in sorted(workbook.cells):
        formula = workbook.cells[cell].formula
        if not formula or cell in input_cells or cell in bad:
            continue
        try:
            ast = _patch_ast(
                substitute_names(parse_formula(formula), workbook), cell, patches, applied
            )
            code[cell] = _Translator(cell).scalar(ast)
            deps[cell] = _refs(ast, _sheet_of(cell))
        except _Unsupported as exc:
            bad.add(cell)
            not_converted.append(NotConverted(cell=cell, reason=str(exc)))
        except FormulaSyntaxError as exc:  # pragma: no cover - caught by subset
            bad.add(cell)
            not_converted.append(NotConverted(cell=cell, reason=f"formula not parsed: {exc}"))

    for d in sorted(patches, key=lambda d: d.decision_id):
        if d.patch and d.decision_id not in applied:
            raise InvalidPatch(
                f"{d.decision_id}: patch matched no comparison in {d.patch.get('cell')}"
            )

    # Dependents of cells the emitter itself rejected.
    changed = True
    while changed:
        changed = False
        for cell in sorted(code):
            if cell in bad:
                continue
            hit = sorted(d for d in deps[cell] if d in bad and d not in input_cells)
            if hit:
                bad.add(cell)
                not_converted.append(
                    NotConverted(
                        cell=cell,
                        reason="depends on not-converted cell " + ", ".join(hit),
                        dependent=True,
                    )
                )
                changed = True

    out_cells = {name: _norm(spec.cell) for name, spec in mapping.outputs.items()}
    outputs = sorted(n for n, c in out_cells.items() if c not in bad)
    omitted = tuple(sorted(n for n, c in out_cells.items() if c in bad))

    # Iterative post-order DFS from the outputs gives a dependency order.
    order: list[str] = []
    seen: set[str] = set()
    needed: set[str] = set()
    for name in outputs:
        root = out_cells[name]
        stack = [(root, False)]
        while stack:
            cell, done = stack.pop()
            if done:
                order.append(cell)
                continue
            if cell in seen:
                continue
            seen.add(cell)
            needed.add(cell)
            if cell in code and cell not in input_cells:
                stack.append((cell, True))
                for d in sorted(deps[cell], reverse=True):
                    if d not in seen:
                        stack.append((d, False))
    formula_order = [c for c in order if c in code and c not in input_cells]
    emitted = set(formula_order)
    if len(emitted) != len(formula_order):  # pragma: no cover
        raise ValueError("circular reference in converted cells")
    # Post-order from a DFS with a seen-set can place a cell before a
    # dependency only on a cycle; reject that rather than emit wrong code.
    position = {c: i for i, c in enumerate(formula_order)}
    for c in formula_order:
        for d in deps[c]:
            if d in position and position[d] > position[c]:
                raise ValueError(f"circular reference involving {c} and {d}")

    consts = sorted(c for c in needed if c not in code and c not in input_cells)
    lines = [_HEADER]
    if not_converted or omitted:
        lines.append("# Not converted (no code generated):")
        for e in sorted(
            not_converted, key=lambda e: (e.dependent, e.cell or "", e.reason)
        ):
            lines.append(f"#   {e.cell}: {e.reason}".replace("\n", " "))
        for name in omitted:
            lines.append(f"#   output {name}: omitted, depends on a not-converted cell")
        lines.append("")
    lines.append("_CONSTS = {")
    for c in consts:
        cell = workbook.cells.get(c)
        lines.append(f"    {c!r}: {_const_code(cell.value if cell else None)},")
    lines.append("}")
    lines.append("")
    lines.append("")
    lines.append("def compute(inputs, trace=None):")
    lines.append("    v = dict(_CONSTS)")
    for name in sorted(in_cells):
        lines.append(f"    v[{in_cells[name]!r}] = _inp(inputs.get({name!r}))")
    for c in formula_order:
        lines.append(f"    v[{c!r}] = {code[c]}")
    lines.append("    return {")
    for name in outputs:
        lines.append(f"        {name!r}: v[{out_cells[name]!r}],")
    lines.append("    }")
    lines.append("")
    return EmitResult("\n".join(lines), tuple(not_converted), omitted)


def emit_python(
    workbook: Workbook,
    mapping: Mapping,
    mode: str = "faithful",
    decisions: list[Decision] | None = None,
) -> str:
    """Return the generated module source (see ``emit_module`` for details)."""
    return emit_module(workbook, mapping, mode, decisions).code
