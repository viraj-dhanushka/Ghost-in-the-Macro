"""Dispatcher for the Kiro hooks in .kiro/hooks/. Run through scripts/ghost-py.

Usage: ghost_hook.py {autopsy|report|verify|golden}
       ghost_hook.py repair <migration-dir>
The hook payload (JSON, on stdin) is searched for the path the hook cares about.
Nothing is invented: output is whatever the Ghost command prints.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

PATTERNS = {
    "autopsy": r'[^"\s]*graveyard/[^/"\s]+\.xls[xm]',
    "report": r'\.kiro/specs/[^/"]+(?=/decisions\.yaml)',
    "verify": r'\.kiro/specs/[^/"]+(?=/(?:logic\.py|mapping\.yaml))',
}


GENERATED_MARK = '"""Generated by Ghost'
LOG_HEADER = (
    "# Repair log\n\n"
    "Written by `scripts/ghost_hook.py repair` after each verification of a hand-written `logic.py`, from the "
    "proof report. Do not edit by hand.\n"
)
NOT_CONVERGED_AFTER = 5


def _round_text(report: dict, brief: dict, now: str, planted: str | None, failed_before: int, number: int) -> str:
    verdict = report.get("passed")
    passed = verdict is True
    result = "PASS" if passed else ("FAIL" if verdict is False else "NOT AVAILABLE")
    counts = ", ".join(f"{report.get(k, 'not checked')} {label}" for k, label in
                       (("cases_generated", "generated"), ("cases_targeted", "targeted"), ("distinct_cases", "distinct")))
    lines = [f"## Round {number}", f"- time: {now}", f"- seed: {report.get('seed', 'not checked')}",
             f"- cases: {counts}", f"- result: {result}"]
    ce = brief.get("counterexample")
    if passed or not ce:
        lines.append("- counterexample: none")
    else:
        out = ce["output"]
        ref = ce["referee"].get(out) if isinstance(ce["referee"], dict) and out in ce["referee"] else ce["referee"]
        act = ce["actual"].get(out) if isinstance(ce["actual"], dict) and out in ce["actual"] else ce["actual"]
        inputs = ", ".join(f"{k}={v}" for k, v in sorted((ce["inputs"] or {}).items()))
        lines.append(f"- counterexample: {inputs}; output {out} ({ce['cell']}): Referee {ref}, actual {act}; "
                     f"rule {brief['rule']['rule_id']}; found by {brief['found_by']}")
    if planted:
        lines.append(f"- planted: {planted}")
    if verdict is False and failed_before + 1 >= NOT_CONVERGED_AFTER:
        lines.append(f"- status: not converged after {failed_before + 1} failed rounds")
    return "\n".join(lines) + "\n"


def repair_step(mdir, now=None, env=None, newer_than_ns=None) -> str:
    """After a verification of a hand-written logic.py: write repair-brief.json and append one block to
    repair-log.md. Does nothing extra for generated or missing code, a missing report, or a report that this
    verification did not write. ``newer_than_ns`` is the report's modification time before the verification ran
    (the verify kind passes it): the report is logged only if verification rewrote it. A direct call has no such
    reference and logs a report that is newer than logic.py and mapping.yaml. The log is written only here, from
    the proof report; nothing but the file's own header says it must not be edited."""
    mdir = Path(mdir)
    env = os.environ if env is None else env
    logic, report_path = mdir / "logic.py", mdir / "proof-report.json"
    if not logic.is_file() or logic.read_text(encoding="utf-8").startswith(GENERATED_MARK):
        return "skipped: logic.py is generated or missing"
    if not report_path.is_file():
        return "skipped: no proof report"
    if newer_than_ns is not None:
        if report_path.stat().st_mtime_ns <= newer_than_ns:
            return "skipped: verification wrote no new proof report"
    else:
        code = [p.stat().st_mtime_ns for p in (logic, mdir / "mapping.yaml") if p.is_file()]
        if report_path.stat().st_mtime_ns < max(code):
            return ("skipped: the proof report is older than logic.py or mapping.yaml "
                    "(verification wrote no new report)")
    import repair_brief
    report = json.loads(report_path.read_text(encoding="utf-8"))
    brief = repair_brief.write_brief(mdir)  # the real brief: the log below records what this round showed
    log = mdir / "repair-log.md"
    text = log.read_text(encoding="utf-8") if log.is_file() else LOG_HEADER
    results = re.findall(r"^- result: (PASS|FAIL|NOT AVAILABLE)$", text, re.M)
    failed_before = 0
    for r in reversed(results):
        if r != "FAIL":
            break
        failed_before += 1
    stamp = now() if now else datetime.now().isoformat(timespec="seconds")
    block = _round_text(report, brief, stamp, (env.get("GHOST_PLANTED") or "").strip() or None,
                        failed_before, len(results) + 1)
    log.write_text(text.rstrip("\n") + "\n\n" + block, encoding="utf-8")
    if report.get("passed") is False and failed_before + 1 >= NOT_CONVERGED_AFTER:
        # The cap: the agent gets a brief with no counterexample to chase, and the status is printed.
        n = failed_before + 1
        (mdir / "repair-brief.json").write_text(json.dumps({
            "status": "not converged", "failed_rounds": n,
            "note": f"{n} failed rounds in a row; stop and tell the user what the last round in repair-log.md showed",
        }, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        return f"logged; status: not converged after {n} failed rounds"
    return "logged"


def main() -> int:
    kind = sys.argv[1] if len(sys.argv) > 1 else ""
    if kind == "repair":
        target = sys.argv[2] if len(sys.argv) > 2 else None
        if target is None:
            m = re.search(PATTERNS["verify"], sys.stdin.read())
            target = m.group(0) if m else None
        if target is None:
            print("ghost_hook repair: no migration folder given; nothing run.")
            return 0
        print(f"ghost_hook repair: {repair_step(target)}")
        return 0
    if kind == "golden":
        proc = subprocess.run(
            [sys.executable, "-m", "pytest", "tests", "-m", "golden", "-q"],
            capture_output=True, text=True,
        )
        sys.stdout.write(proc.stdout + proc.stderr)
        if proc.returncode == 5:  # pytest: no tests collected/selected
            # Safety net: golden tests exist (tests/golden/), so this only fires if the
            # selection becomes empty again (marker removed or tests deleted).
            print("GOLDEN HOOK: NOT CHECKED. 0 golden tests are selected "
                  "(no test carries @pytest.mark.golden).")
            return 1
        return proc.returncode
    if kind not in PATTERNS:
        print(f"ghost_hook: unknown kind {kind!r}", file=sys.stderr)
        return 1
    m = re.search(PATTERNS[kind], sys.stdin.read())
    if not m:
        print(f"ghost_hook {kind}: no matching path in the hook payload; nothing run.")
        return 0
    target = m.group(0)
    sub = {"autopsy": "autopsy", "report": "report", "verify": "verify"}[kind]
    report = Path(target) / "proof-report.json"
    before = report.stat().st_mtime_ns if report.is_file() else -1
    rc = subprocess.call([sys.executable, "-m", "ghost.cli", sub, target])
    if kind == "verify" and rc in (0, 1):  # 0 pass, 1 mismatch (1 is also a caught error: the mtime check decides)
        print(f"ghost_hook repair: {repair_step(target, newer_than_ns=before)}")
    return rc


if __name__ == "__main__":
    sys.exit(main())
