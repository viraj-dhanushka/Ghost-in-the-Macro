"""Generate sample (a): the discount calculator (generated, deterministic).

Run: python samples/make_discount.py [output.xlsx]

The workbook is written with openpyxl, so it carries formulas only and no
Excel-saved values.
"""

from __future__ import annotations

import sys
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill
from openpyxl.worksheet.datavalidation import DataValidation

DEFAULT_OUT = Path(__file__).parent / "discount.xlsx"
LABEL = "generated by samples/make_discount.py"

INPUT_FILL = PatternFill("solid", start_color="FFF2CC", end_color="FFF2CC")
OUTPUT_FILL = PatternFill("solid", start_color="C6E0B4", end_color="C6E0B4")

TESTS_ROWS = 200


def test_rows() -> list[tuple[int, str, int]]:
    """200 fixed (quantity, unit price, distance) rows, no randomness."""
    quantities = [0, 1, 2, 5, 10, 25, 48, 49, 50, 51, 75, 100, 250, 500, 1000]
    prices = ["0.01", "0.10", "1.00", "2.50", "9.99", "19.95", "49.50", "100.00"]
    distances = [0, 1, 5, 9, 10, 11, 15, 20, 37, 100]
    rows = []
    for i in range(TESTS_ROWS):
        rows.append(
            (
                quantities[i % len(quantities)],
                prices[(i * 3 + i // 8) % len(prices)],
                distances[(i * 7 + i // 5) % len(distances)],
            )
        )
    return rows


def build(path: Path = DEFAULT_OUT) -> Path:
    wb = Workbook()
    ws = wb.active
    ws.title = "Calculator"

    ws["A1"] = "Discount calculator"
    ws["A1"].font = Font(bold=True)
    ws["D1"] = LABEL

    # Inputs
    ws["A2"], ws["B2"] = "Quantity", 10
    ws["A3"], ws["B3"] = "Unit price", 19.95
    ws["A4"], ws["B4"] = "Delivery distance (km)", 12
    for ref in ("B2", "B3", "B4"):
        ws[ref].fill = INPUT_FILL

    dv_q = DataValidation(type="whole", operator="greaterThanOrEqual", formula1="0")
    dv_p = DataValidation(type="decimal", operator="greaterThanOrEqual", formula1="0")
    dv_d = DataValidation(type="decimal", operator="greaterThanOrEqual", formula1="0")
    for dv, ref in ((dv_q, "B2"), (dv_p, "B3"), (dv_d, "B4")):
        ws.add_data_validation(dv)
        dv.add(ref)

    # Parameters
    ws["D2"], ws["E2"] = "Bulk threshold (units)", 50
    ws["D3"], ws["E3"] = "Bulk discount rate", 0.10
    ws["D4"], ws["E4"] = "Base delivery fee", 5
    ws["D5"], ws["E5"] = "Free delivery within (km)", 10
    ws["D6"], ws["E6"] = "Fee per extra km", 0.40
    ws["D7"], ws["E7"] = "VAT rate", 0.20

    # Calculation
    ws["A6"], ws["B6"] = "Subtotal", "=B2*B3"
    ws["A7"], ws["B7"] = "Discount", "=IF(B2>=E2,ROUND(B6*E3,2),0)"
    ws["A8"], ws["B8"] = "Net goods", "=B6-B7"
    ws["A9"], ws["B9"] = (
        "Delivery fee",
        "=IF(B2>=E2,0,ROUND(E4+MAX(0,B4-E5)*E6,2))",
    )
    ws["A10"], ws["B10"] = "VAT", "=ROUND((B8+B9)*E7,2)"
    ws["A11"], ws["B11"] = "Total", "=B8+B9+B10"
    ws["A11"].font = Font(bold=True)
    ws["B11"].fill = OUTPUT_FILL
    ws.column_dimensions["A"].width = 26
    ws.column_dimensions["D"].width = 28

    # Tests sheet: 200 fixed rows of inputs
    tests = wb.create_sheet("Tests")
    tests["A1"], tests["B1"], tests["C1"] = "Quantity", "Unit price", "Distance"
    tests["E1"] = LABEL
    for r, (q, p, d) in enumerate(test_rows(), start=2):
        tests.cell(r, 1, q)
        tests.cell(r, 2, float(p))
        tests.cell(r, 3, d)

    wb.properties.title = "Discount calculator (generated)"
    wb.properties.creator = "ghost samples (generated)"
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    print(build(out))
