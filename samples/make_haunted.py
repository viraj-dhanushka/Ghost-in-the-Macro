"""Generate sample (b): the haunted discount calculator (generated, deterministic).

Run: python samples/make_haunted.py [output.xlsx]

Same as sample (a) except for one planted inconsistency: the bulk discount
applies at quantity >= 50 (B2>=E2) while free delivery applies only at
quantity > 50 (B2>50). At quantity 50 the customer gets the discount but still
pays delivery. Carries formulas only, no Excel-saved values.
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

from openpyxl import load_workbook

sys.path.insert(0, str(Path(__file__).parent))
import make_discount  # noqa: E402

DEFAULT_OUT = Path(__file__).parent / "haunted.xlsx"
LABEL = "generated by samples/make_haunted.py"

DISCOUNT_FORMULA = "=IF(B2>=E2,ROUND(B6*E3,2),0)"  # >= 50
HAUNTED_DELIVERY = "=IF(B2>50,0,ROUND(E4+MAX(0,B4-E5)*E6,2))"  # > 50 (the ghost)


def build(path: Path = DEFAULT_OUT) -> Path:
    with tempfile.TemporaryDirectory() as tmp:
        base = make_discount.build(Path(tmp) / "base.xlsx")
        wb = load_workbook(base)
    ws = wb["Calculator"]
    assert ws["B7"].value == DISCOUNT_FORMULA, ws["B7"].value
    ws["B9"] = HAUNTED_DELIVERY
    ws["A1"] = "Discount calculator (haunted)"
    ws["D1"] = LABEL
    wb["Tests"]["E1"] = LABEL
    wb.properties.title = "Haunted discount calculator (generated)"
    wb.properties.creator = "ghost samples (generated)"
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    print(build(out))
