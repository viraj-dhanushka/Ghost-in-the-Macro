"""Generate sample (d): the macro workbook pair (generated, deterministic).

Run: python samples/make_xlsm.py [output_dir]

Writes two ``.xlsm`` files built through the Referee's ``save_with_vba``:

* ``discount_vba.xlsm``: the discount calculator plus a VBA function
  ``DeliveryFee`` (used as ``=DeliveryFee(B2,B4)`` in ``Calculator!B13``) and a
  button macro ``AwardPoints`` (points = whole tens of the total, Gold from 500).
* ``haunted_vba.xlsm``: the same workbook whose macro rounds total/10 instead of
  taking whole tens (the haunted twin: a total of 95 earns 10 points, not 9).

No macro is ever run. The base workbook is opened with macros off
(``NEVER_EXECUTE``); the VBA text is only attached to the document and stored.
Needs LibreOffice. Output is generated, never hand-edited, and not committed.
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

from openpyxl import load_workbook

sys.path.insert(0, str(Path(__file__).parent))
import make_discount  # noqa: E402

DEFAULT_DIR = Path(__file__).parent
LABEL = "generated by samples/make_xlsm.py"
MODULE_NAME = "Module1"

DELIVERY_FEE_VBA = """\
' generated by samples/make_xlsm.py
Function DeliveryFee(quantity As Double, distanceKm As Double) As Double
    If quantity >= 50 Then
        DeliveryFee = 0
    Else
        Dim extraKm As Double
        extraKm = distanceKm - 10
        If extraKm < 0 Then extraKm = 0
        DeliveryFee = Application.WorksheetFunction.Round(5 + extraKm * 0.4, 2)
    End If
End Function
"""

AWARD_POINTS_FAITHFUL = """\
Sub AwardPoints()
    Dim total As Double
    total = Range("B11").Value
    Range("B14").Value = Int(total / 10)
    If total >= 500 Then
        Range("B15").Value = "Gold"
    Else
        Range("B15").Value = "Standard"
    End If
End Sub
"""

# the ghost: rounds total/10 instead of taking whole tens
AWARD_POINTS_HAUNTED = AWARD_POINTS_FAITHFUL.replace(
    "Int(total / 10)", "Application.WorksheetFunction.Round(total / 10, 0)"
)

FAITHFUL_SOURCE = DELIVERY_FEE_VBA + "\n" + AWARD_POINTS_FAITHFUL
HAUNTED_SOURCE = DELIVERY_FEE_VBA + "\n" + AWARD_POINTS_HAUNTED


def _build_base(path: Path) -> Path:
    """Discount calculator plus the cells the macros use (formulas only, no VBA)."""
    base = make_discount.build(path)
    wb = load_workbook(base)
    ws = wb["Calculator"]
    ws["D1"] = LABEL
    ws["A13"], ws["B13"] = "Delivery fee (VBA)", "=DeliveryFee(B2,B4)"
    ws["A14"], ws["B14"] = "Points (set by AwardPoints)", 0
    ws["A15"], ws["B15"] = "Tier (set by AwardPoints)", "Standard"
    wb.properties.title = "Discount calculator with macros (generated)"
    wb.save(base)
    return base


def build_pair(out_dir: Path = DEFAULT_DIR, soffice_path: str | None = None) -> tuple[Path, Path]:
    """Build (discount_vba.xlsm, haunted_vba.xlsm) in ``out_dir`` through the Referee."""
    from ghost.referee.client import RefereeClient

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    targets = (
        (out_dir / "discount_vba.xlsm", FAITHFUL_SOURCE),
        (out_dir / "haunted_vba.xlsm", HAUNTED_SOURCE),
    )
    with tempfile.TemporaryDirectory() as tmp:
        base = _build_base(Path(tmp) / "base.xlsx")
        for target, source in targets:
            # run_macros stays False: macros are off, nothing is executed
            with RefereeClient(soffice_path, base, run_macros=False, job_dir=tmp) as ref:
                ref.open(base)
                ref.save_with_vba(target, {MODULE_NAME: source})
    return targets[0][0], targets[1][0]


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DIR
    for p in build_pair(out):
        print(p)
