"""Generate sample (c): multi-scenario tax-style model (generated, deterministic).

Run: python samples/make_scenarios.py [output.xlsx]

Four inputs feed ten scenarios. The best (lowest net cost) scenario is picked
with MAX plus INDEX/MATCH. Only the P0 formula subset is used. The workbook is
written with openpyxl, so it carries formulas only and no Excel-saved values.
"""

from __future__ import annotations

import sys
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill

DEFAULT_OUT = Path(__file__).parent / "scenarios.xlsx"
LABEL = "generated by samples/make_scenarios.py"

INPUT_FILL = PatternFill("solid", start_color="FFF2CC", end_color="FFF2CC")
OUTPUT_FILL = PatternFill("solid", start_color="C6E0B4", end_color="C6E0B4")

# (name, tax rate, standard deduction, credit rate, fixed fee)
SCENARIOS = [
    ("Flat 20", "0.20", 0, "0.00", 0),
    ("Flat 25 + deduction", "0.25", 2000, "0.00", 0),
    ("Low rate, high fee", "0.15", 0, "0.00", 1500),
    ("Credit A", "0.22", 1000, "0.05", 100),
    ("Credit B", "0.24", 500, "0.08", 250),
    ("Deduction heavy", "0.30", 5000, "0.00", 300),
    ("Hybrid", "0.18", 1500, "0.02", 600),
    ("Premium", "0.12", 0, "0.00", 3000),
    ("Family", "0.21", 3000, "0.04", 200),
    ("Minimal", "0.10", 0, "0.00", 4500),
]
FIRST = 6
LAST = FIRST + len(SCENARIOS) - 1  # 15


def build(path: Path = DEFAULT_OUT) -> Path:
    wb = Workbook()
    ws = wb.active
    ws.title = "Model"

    ws["A1"] = "Scenario tax model"
    ws["A1"].font = Font(bold=True)
    ws["H1"] = LABEL

    ws["A2"], ws["B2"] = "Gross income", 60000
    ws["A3"], ws["B3"] = "Dependants", 2
    ws["D2"], ws["E2"] = "Other deductions", 1200
    ws["D3"], ws["E3"] = "Dependant allowance", 800
    for ref in ("B2", "B3", "E2", "E3"):
        ws[ref].fill = INPUT_FILL

    headers = ["Scenario", "Rate", "Deduction", "Credit rate", "Fixed fee", "Net cost"]
    for c, h in enumerate(headers, start=1):
        ws.cell(5, c, h).font = Font(bold=True)

    for i, (name, rate, ded, credit, fee) in enumerate(SCENARIOS):
        r = FIRST + i
        ws.cell(r, 1, name)
        ws.cell(r, 2, float(rate))
        ws.cell(r, 3, ded)
        ws.cell(r, 4, float(credit))
        ws.cell(r, 5, fee)
        # taxable income, tax, credit and fee combined into one net cost
        ws.cell(
            r,
            6,
            f"=ROUND(MAX(0,$B$2-C{r}-$E$2-$B$3*$E$3)*B{r}"
            f"-$B$2*D{r}+E{r},2)",
        )

    # Best scenario = lowest net cost. MAX over negated costs via helper column.
    ws["H5"] = "Negated cost"
    ws["H5"].font = Font(bold=True)
    for r in range(FIRST, LAST + 1):
        ws.cell(r, 8, f"=-F{r}")

    ws["A18"], ws["B18"] = "Best (max negated cost)", f"=MAX(H{FIRST}:H{LAST})"
    ws["A19"], ws["B19"] = "Best scenario", f"=INDEX(A{FIRST}:A{LAST},MATCH(B18,H{FIRST}:H{LAST},0))"
    ws["A20"], ws["B20"] = "Best net cost", f"=-B18"
    ws["A19"].font = Font(bold=True)
    ws["B19"].fill = OUTPUT_FILL
    ws["B20"].fill = OUTPUT_FILL
    ws.column_dimensions["A"].width = 26
    ws.column_dimensions["D"].width = 22

    wb.properties.title = "Scenario model (generated)"
    wb.properties.creator = "ghost samples (generated)"
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    print(build(out))
