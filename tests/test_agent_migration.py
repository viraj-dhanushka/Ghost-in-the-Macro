def test_the_graveyard_workbook_is_what_the_sample_script_generates():
    import openpyxl
    spec = importlib.util.spec_from_file_location("make_haunted", ROOT / "samples" / "make_haunted.py")
    mod = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(ROOT / "samples"))
    try:
        spec.loader.exec_module(mod)
    finally:
        sys.path.remove(str(ROOT / "samples"))
    fresh = Path(mod.build(Path(tempfile.mkdtemp()) / "w.xlsx"))

    def cells(p):
        ws = openpyxl.load_workbook(p)["Calculator"]
        return {c.coordinate: c.value for row in ws.iter_rows() for c in row if c.value is not None}

    assert cells(ROOT / "graveyard" / "haunted.xlsx") == cells(fresh)
    assert "generated by samples/make_haunted.py" in cells(fresh).values()


@pytest.mark.skipif(not _has_soffice(), reason="LibreOffice not installed")
def test_the_committed_logic_still_passes_against_the_referee_on_a_copy(tmp_path):
    work = tmp_path / "m"
    shutil.copytree(M, work)
    proc = subprocess.run([sys.executable, "-m", "ghost.cli", "verify", str(work), "--mode", "faithful",
                           "--workbook", str(ROOT / "graveyard" / "haunted.xlsx")],
                          cwd=ROOT, capture_output=True, text=True, timeout=600, stdin=subprocess.DEVNULL)
    assert proc.returncode == 0, proc.stdout[-600:] + proc.stderr[-300:]
    assert "[faithful] PASS" in proc.stdout
    # the committed folder itself is untouched by the re-run on the copy
    assert (M / "repair-log.md").read_text(encoding="utf-8").count("## Round ") == 4


def test_logic_py_is_byte_for_byte_the_one_the_readme_names():
    import hashlib
    text = (M / "README.md").read_text(encoding="utf-8")
    digest = re.search(r"`([0-9a-f]{64})`", text).group(1)
    assert hashlib.sha256((M / "logic.py").read_bytes()).hexdigest() == digest


