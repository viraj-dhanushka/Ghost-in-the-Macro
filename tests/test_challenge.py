BAD_WORDS = re.compile(r"\b(correct|proven|proved)\b", re.I)


@needs_soffice
def test_honest_candidate_passes_and_nothing_leaks(haunted, tmp_path, capsys):
    code_file = SUSPECTS / "haunted" / "honest.py"
    before = (_sha(haunted), _sha(code_file))
    code, out, err = _run(capsys, haunted, "--code", code_file)
    assert code == 0, out + err
    assert re.search(r"no difference found on \d+ cases", out)
    assert f"seed {SEED}" in out
    assert "LibreOffice" in out
    assert "not confirmed by a person" in out
    for name in ("quantity", "unit_price", "delivery_distance_km", "total"):
        assert name in out
    assert "generated" in out and "targeted" in out and "distinct" in out
    assert (_sha(haunted), _sha(code_file)) == before
    assert not BAD_WORDS.search(out + err)
    for text in (out, err):
        assert "/tmp" not in text and "/var/" not in text and str(tmp_path) not in text
        assert "ghost-challenge" not in text


