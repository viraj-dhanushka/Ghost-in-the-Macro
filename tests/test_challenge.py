def test_nothing_under_web_imports_challenge_or_load_compute():
    bad = []
    for py in (ROOT / "web").rglob("*.py"):
        tree = ast.parse(py.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            names = []
            if isinstance(node, ast.Import):
                names = [a.name for a in node.names]
            elif isinstance(node, ast.ImportFrom):
                names = [node.module or ""] + [a.name for a in node.names]
            elif isinstance(node, ast.Name):
                names = [node.id]
            elif isinstance(node, ast.Attribute):
                names = [node.attr]
            if any(n == "load_compute" or n.startswith("ghost.challenge") or n == "challenge" and
                   isinstance(node, ast.ImportFrom) for n in names):
                bad.append(f"{py.name}:{node.lineno}")
    assert bad == []


