def _has_soffice() -> bool:
    try:
        locate_soffice()
        return True
    except RefereeUnavailable:
        return False


needs_soffice = pytest.mark.skipif(not _has_soffice(), reason="LibreOffice not installed")


def _build(name: str, dest: Path) -> Path:
    spec = importlib.util.spec_from_file_location(f"_mk_{name}", ROOT / "samples" / f"make_{name}.py")
    mod = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(ROOT / "samples"))
    try:
        spec.loader.exec_module(mod)
    finally:
        sys.path.remove(str(ROOT / "samples"))
    return Path(mod.build(dest))


@pytest.fixture(scope="module")
def haunted(tmp_path_factory) -> Path:
    return _build("haunted", tmp_path_factory.mktemp("wb") / "haunted.xlsx")


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def _run(capsys, *argv: str) -> tuple[int, str, str]:
    code = cli.main(["challenge", *map(str, argv)])
    cap = capsys.readouterr()
    return code, cap.out, cap.err


def _write(tmp_path: Path, text: str, name: str = "cand.py") -> Path:
    p = tmp_path / name
    p.write_text(text, encoding="utf-8")
    return p


def _one_line_error(err: str) -> None:
    lines = [ln for ln in err.splitlines() if ln.strip()]
    assert len(lines) == 1, err
    assert lines[0].startswith("ghost: error:")
    assert "Traceback" not in err


