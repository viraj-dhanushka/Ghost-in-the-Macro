def test_property_2_a_counterexample_reproduces(haunted, tmp_path, capsys, suspect):
    """Property 2: re-evaluating the reported inputs on the Referee and on the Candidate gives the
    reported values. Validates Requirements 1.5 and 2.6."""
    sys.path.insert(0, str(ROOT / "scripts"))
    try:
        import lineup
    finally:
        sys.path.remove(str(ROOT / "scripts"))
    out_dir = tmp_path / "kept"
    code, out, err = _run(capsys, haunted, "--code", SUSPECTS / "haunted" / f"{suspect}.py", "--out", out_dir)
    assert code == 1
    report = json.loads((out_dir / "proof-report.json").read_text(encoding="utf-8"))
    m = next(x for x in report["mismatches"] if x.get("minimal") is True)
    referee, candidate = lineup.evaluate("haunted", suspect, m["inputs"])
    assert referee == float(m["expected"]["total"])
    assert candidate == float(m["actual"]["total"])
    assert f"{float(m['expected']['total'])!r}" in out


