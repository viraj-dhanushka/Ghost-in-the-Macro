"""The suspects and the line-up (trial-by-workbook, Requirement 2 and Properties 1 and 2).

Written before `scripts/lineup.py` and `samples/suspects/*/lineup.json` exist. The structural tests need no
LibreOffice; the Referee-backed tests are skipped when it is not installed.
"""
from __future__ import annotations

import importlib.util
import json
import re
import sys
import tempfile
from decimal import Decimal
from pathlib import Path

import pytest

from ghost.referee.locate import RefereeUnavailable, locate_soffice

ROOT = Path(__file__).resolve().parent.parent
SUSPECTS = ROOT / "samples" / "suspects"
WORKBOOKS = {"haunted": "make_haunted.py", "discount": "make_discount.py"}
EXPECTED = {
    "haunted": ["dropped_branch", "float_rounding", "honest", "tidied"],
    "discount": ["dropped_branch", "float_rounding", "gt_slip", "honest"],
}


def _has_soffice():
    try:
        locate_soffice()
        return True
    except RefereeUnavailable:
        return False


needs_soffice = pytest.mark.skipif(not _has_soffice(), reason="LibreOffice not installed")


def _load(path: Path):
    spec = importlib.util.spec_from_file_location(f"suspect_{path.parent.name}_{path.stem}", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _lineup(name):
    return json.loads((SUSPECTS / name / "lineup.json").read_text(encoding="utf-8"))


def _lineup_script():
    sys.path.insert(0, str(ROOT / "scripts"))
    try:
        import lineup
        return lineup
    finally:
        sys.path.remove(str(ROOT / "scripts"))


# -- structure -------------------------------------------------------------------------------

@pytest.mark.parametrize("name", sorted(EXPECTED))
def test_each_workbook_has_its_suspects_and_a_pinned_mapping(name):
    files = sorted(p.stem for p in (SUSPECTS / name).glob("*.py"))
    assert files == EXPECTED[name]
    mapping = (SUSPECTS / name / "mapping.yaml").read_text(encoding="utf-8")
    assert "cell: Calculator!B2" in mapping and "cell: Calculator!B11" in mapping
    assert "quantity:" in mapping and "total:" in mapping


@pytest.mark.parametrize("name", sorted(EXPECTED))
def test_every_suspect_is_a_pure_compute_function_that_says_how_it_was_written(name):
    for stem in EXPECTED[name]:
        path = SUSPECTS / name / f"{stem}.py"
        text = path.read_text(encoding="utf-8")
        assert not text.startswith('"""Generated by Ghost'), path  # must be verified as hand-written code
        header = text.split('"""')[1]
        assert "not produced by Ghost's transpiler" in header and "Planted difference:" in header
        assert "Measured result:" in header
        # No AI authorship is claimed: no prompt is committed beside the suspects.
        assert "Author: not recorded." in header, path
        assert not re.search(r"\b(authored|written|generated|translated) by\b|AI-written|\bthe the\b", header, re.I), path
        mod = _load(path)
        out = mod.compute({"quantity": 10, "unit_price": Decimal("19.95"), "delivery_distance_km": Decimal("12")})
        assert set(out) == {"total"}
        assert float(out["total"]) == pytest.approx(246.36)  # the workbook's own value at the defaults


def test_the_suspects_match_the_workbook_cells_they_are_pinned_to():
    root = ROOT / "samples"
    sys.path.insert(0, str(root))
    try:
        for name, script in WORKBOOKS.items():
            spec = importlib.util.spec_from_file_location(f"w_{name}", root / script)
            mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(mod)
            from ghost.ingest.workbook import load_workbook
            wb = load_workbook(str(mod.build(Path(tempfile.mkdtemp()) / "w.xlsx")))
            for cell in ("Calculator!B2", "Calculator!B3", "Calculator!B4", "Calculator!B11"):
                assert cell in wb.cells, (name, cell)
    finally:
        sys.path.remove(str(root))


# -- measured labels -------------------------------------------------------------------------

@pytest.mark.parametrize("name", sorted(EXPECTED))
def test_lineup_json_covers_every_suspect_and_has_no_path_or_timestamp(name):
    data = _lineup(name)
    assert [s["suspect"] for s in data["suspects"]] == EXPECTED[name]
    assert data["seed"] == 20261204 and data["libreoffice"]
    blob = json.dumps(data)
    assert "/Users/" not in blob and "/tmp/" not in blob and not re.search(r"\d{4}-\d{2}-\d{2}T", blob)
    for s in data["suspects"]:
        assert s["exit_code"] in (0, 1)
        if s["exit_code"] == 0:
            assert s["verdict"].startswith("no difference found on ") and s["counterexample"] is None
        else:
            assert s["counterexample"]["inputs"] and "referee" in s["counterexample"] and "candidate" in s["counterexample"]
            assert s["how_found"] in ("targeted boundary case, not shrunk", "shrunk")


@pytest.mark.parametrize("name", sorted(EXPECTED))
def test_each_header_label_is_the_measured_result(name):
    script = _lineup_script()
    for s in _lineup(name)["suspects"]:
        header = (SUSPECTS / name / f"{s['suspect']}.py").read_text(encoding="utf-8").split('"""')[1]
        line = next(l for l in header.splitlines() if l.startswith("Measured result:"))
        assert line == "Measured result: " + script.label_for(s), (name, s["suspect"])


def test_the_labels_never_use_the_word_correct():
    script = _lineup_script()
    for name in EXPECTED:
        for s in _lineup(name)["suspects"]:
            assert not re.search(r"\b(correct|proven|proved)\b", script.label_for(s), re.I)


@pytest.mark.parametrize("name, suspect", [("haunted", "honest"), ("discount", "honest")])
def test_the_honest_suspect_is_measured_as_not_convicted(name, suspect):
    s = next(x for x in _lineup(name)["suspects"] if x["suspect"] == suspect)
    assert s["exit_code"] == 0


def test_the_tidied_and_dropped_branch_suspects_are_convicted_at_quantity_50_or_above():
    haunted = {s["suspect"]: s for s in _lineup("haunted")["suspects"]}
    assert haunted["tidied"]["exit_code"] == 1 and haunted["dropped_branch"]["exit_code"] == 1
    assert int(haunted["tidied"]["counterexample"]["inputs"]["quantity"]) == 50


# -- Referee-backed properties ---------------------------------------------------------------

@needs_soffice
@pytest.mark.parametrize("name", sorted(EXPECTED))
@pytest.mark.parametrize("seed", [1, 7, 20261204])
def test_property_1_the_honest_suspect_is_never_convicted_across_seeds(name, seed):
    # Feature: trial-by-workbook, Property 1: an honest suspect is never convicted
    script = _lineup_script()
    r = script.challenge(name, "honest", seed=seed)
    assert r["exit_code"] == 0 and r["counterexample"] is None, r


@needs_soffice
@pytest.mark.parametrize("name", sorted(EXPECTED))
def test_property_2_every_reported_counterexample_reproduces_on_the_referee_and_the_suspect(name):
    # Feature: trial-by-workbook, Property 2: a counterexample reproduces
    script = _lineup_script()
    convicted = [s for s in _lineup(name)["suspects"] if s["exit_code"] == 1]
    assert convicted, "the line-up should convict at least one suspect"
    for s in convicted:
        ce = s["counterexample"]
        referee, candidate = script.evaluate(name, s["suspect"], ce["inputs"])
        assert referee == pytest.approx(ce["referee"], abs=1e-6), s["suspect"]
        assert candidate == pytest.approx(ce["candidate"], abs=1e-6), s["suspect"]
        assert abs(referee - candidate) > 1e-6, s["suspect"]  # and it really is a difference


def test_the_float_rounding_header_claims_only_what_was_measured():
    for name in EXPECTED:
        header = (SUSPECTS / name / "float_rounding.py").read_text(encoding="utf-8").split('"""')[1]
        assert "Python round() on binary floats in place of the worksheet ROUND" in header
        assert "rounded to even" not in header


def test_labels_are_lossless():
    script = _lineup_script()
    entry = {"suspect": "x", "exit_code": 1, "seed": 1, "how_found": "shrunk",
             "counterexample": {"inputs": {"q": "1"}, "referee": 1234567.891, "candidate": 1234567.89}}
    assert "Referee 1234567.891, suspect 1234567.89" in script.label_for(entry)
